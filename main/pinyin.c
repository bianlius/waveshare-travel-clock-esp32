#define TABLE_SIZE (sizeof(pinyin_to_hanzi) / sizeof(pinyin_to_hanzi[0]))

// ==================== 二分查找拼音 ====================
static int find_pinyin_index(const char* pinyin) {
    int left = 0, right = TABLE_SIZE / 2 - 1;
    
    while (left <= right) {
        int mid = (left + right) / 2;
        int cmp = strcmp(pinyin, pinyin_to_hanzi[mid * 2]);
        
        if (cmp == 0) {
            return mid * 2;
        } else if (cmp < 0) {
            right = mid - 1;
        } else {
            left = mid + 1;
        }
    }
    return -1;
}

// ==================== 主检索函数 ====================
uint16_t search_by_pinyin(const char* pinyin, PinyinResult* result) {
    if (pinyin == NULL || result == NULL) {
        return 0;
    }
    
    // 初始化结果
    memset(result->buffer, 0, sizeof(result->buffer));
    result->hanzi_list = NULL;
    result->count = 0;
    
    // 查找拼音
    int idx = find_pinyin_index(pinyin);
    if (idx < 0) {
        return 0;
    }
    
    // 获取汉字串
    const char* hanzi_str = pinyin_to_hanzi[idx + 1];
    uint16_t len = strlen(hanzi_str);
    
    // 复制到缓冲区（每个汉字占3字节UTF-8）
    if (len < sizeof(result->buffer)) {
        strcpy(result->buffer, hanzi_str);
        result->count = len / 2;  // UTF-8中每个汉字占3字节
    }
    
    return result->count;
}

const char* get_hanzi_at(PinyinResult* result, uint16_t index) {
    if (result == NULL || index >= result->count) {
        return NULL;
    }
    return result->buffer + (index * 2);
}