"""Pack pinned Pokémon PNG strips into GVIEW animations.

Pillow is needed only when regenerating these assets, not for an ESP-IDF build.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct

from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/pokemon_followers"
OUTPUT = ROOT / "main/pic_data/pocketMon/followers.h"
MAX_ANIMATION_BYTES = (1 << 31) - 1  # DisplayObject uses a signed 32-bit offset.


def rgb565(pixel):
    r, g, b, alpha = pixel
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) if alpha >= 128 else None


def load_frames(entry):
    path = ASSETS / entry["file"]
    if hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
        raise ValueError(f"Source checksum changed: {path}")
    image = Image.open(path).convert("RGBA")
    dimensions = entry.get("frame_dimensions", [[entry["frame_width"], entry["frame_height"]]] * entry["frames"])
    if len(dimensions) != entry["frames"] or image.size != (sum(w for w, _ in dimensions), max(h for _, h in dimensions)):
        raise ValueError(f"Unexpected strip dimensions: {path}: {image.size}")
    frames, left = [], 0
    for width, height in dimensions:
        frames.append(image.crop((left, 0, left + width, height)))
        left += width
    if entry["flip_x"]:
        frames = [ImageOps.mirror(frame) for frame in frames]
    scale = entry.get("scale_percent", 100)
    if scale != 100:
        size = ((width * scale + 50) // 100, (height * scale + 50) // 100)
        frames = [frame.resize(size, Image.Resampling.NEAREST) for frame in frames]
    if entry.get("align_opaque_bottom"):
        bottoms = [frame.getchannel("A").getbbox()[3] for frame in frames]
        target_bottom = max(bottoms)
        aligned = []
        for frame, bottom in zip(frames, bottoms):
            canvas = Image.new("RGBA", frame.size)
            canvas.alpha_composite(frame, (0, target_bottom - bottom))
            aligned.append(canvas)
        frames = aligned
    return frames


def pack(entry, frames):
    if entry.get("depth") == 13:
        # Preserve the firmware's RGB454 colors and all eight alpha levels.
        header, body = bytearray((13, len(frames))), bytearray()
        offsets = entry.get("frame_offsets", [[0, 0]] * len(frames))
        assert len(offsets) == len(frames)
        for frame, (dx, dy) in zip(frames, offsets):
            if 2 + 7 * len(frames) + len(body) > MAX_ANIMATION_BYTES:
                raise ValueError(f"Frame start exceeds GVIEW offset range: {entry['file']}")
            header.extend(struct.pack(">HHBBB", *frame.size, 127 + dx, 127 + dy, entry["frame_ticks"]))
            for r, g, b, a in frame.getdata():
                color = (round(a * 7 / 255) << 13) | (round(r * 15 / 255) << 9) | (round(g * 31 / 255) << 4) | round(b * 15 / 255)
                body.extend(struct.pack(">H", color))
        return bytes(header + body)
    width, height = frames[0].size
    pixels = [[rgb565(p) for p in frame.getdata()] for frame in frames]
    colors = sorted({color for frame in pixels for color in frame if color is not None})
    # Mudkip needs 16 opaque colors. Keep all of them in RGB565 instead of
    # dropping a shade to make room for the indexed transparency entry.
    depth = 4 if len(colors) <= 15 else 16
    header = bytearray((depth, len(frames)))
    for _ in frames:
        header.extend(struct.pack(">HHBBB", width, height, 127, 127, entry["frame_ticks"]))
    body = bytearray()
    for frame in pixels:
        if depth == 16:
            for color in frame:
                if color == 1:
                    raise ValueError("Opaque color conflicts with RGB565 transparency")
                body.extend(struct.pack("<H", 1 if color is None else color))
        else:
            palette = b"".join(struct.pack(">H", color) for color in colors)
            body.extend(palette.ljust(30, b"\0"))
            lookup = {color: i for i, color in enumerate(colors)}
            indices = [15 if color is None else lookup[color] for color in frame]
            for i in range(0, len(indices), 2):
                body.append(indices[i] | ((indices[i + 1] if i + 1 < len(indices) else 15) << 4))
    data = bytes(header + body)
    if len(data) > MAX_ANIMATION_BYTES:
        raise ValueError(f"Animation exceeds GVIEW's frame offset range: {entry['file']}")
    return data


def header_text(animations):
    lines = ["#ifndef GVIEW_POKEMON_FOLLOWERS_H", "#define GVIEW_POKEMON_FOLLOWERS_H",
             "// Generated by tools/pack_pokemon_followers.py. Sources and credits:",
             "// assets/pokemon_followers/manifest.json and README.md."]
    for entry, data, _ in animations:
        width = (entry["frame_width"] * entry.get("scale_percent", 100) + 50) // 100
        height = (entry["frame_height"] * entry.get("scale_percent", 100) + 50) // 100
        lines.extend((f"// {entry['file']}: {width}x{height}, "
                      f"{entry['frames']} frames, {data[0]}-bit, facing right.",
                      f"const unsigned char {entry['symbol']}[] = {{"))
        for start in range(0, len(data), 24):
            lines.append("    " + ",".join(f"0x{x:02x}" for x in data[start:start + 24]) + ",")
        lines.append("};")
    return "\n".join(lines + ["#endif", ""])


def preview_frames(entry, frames):
    offsets = entry.get("frame_offsets", [[0, 0]] * len(frames))
    left = min(-(f.width // 2) + dx for f, (dx, _) in zip(frames, offsets))
    top = min(-(f.height // 2) + dy for f, (_, dy) in zip(frames, offsets))
    right = max(f.width - f.width // 2 + dx for f, (dx, _) in zip(frames, offsets))
    bottom = max(f.height - f.height // 2 + dy for f, (_, dy) in zip(frames, offsets))
    tiles = []
    for f, (dx, dy) in zip(frames, offsets):
        tile = Image.new("RGBA", (right - left, bottom - top))
        tile.alpha_composite(f, (-(f.width // 2) + dx - left, -(f.height // 2) + dy - top))
        tiles.append(tile)
    return tiles


def previews(animations):
    animations = [(entry, data, preview_frames(entry, frames)) for entry, data, frames in animations]
    out = ROOT / "build/pokemon_followers"
    out.mkdir(parents=True, exist_ok=True)
    width = max(frames[0].width * entry["frames"] * 2 + 16
                for entry, _, frames in animations)
    height = sum(frames[0].height * 2 + 30 for _, _, frames in animations)
    sheet = Image.new("RGB", (width, height), "#e9ecef")
    draw = ImageDraw.Draw(sheet)
    y = 4
    for entry, _, frames in animations:
        draw.text((8, y), f"{entry['file']}  {frames[0].width}x{frames[0].height}", fill="black")
        y += 18
        sequence = []
        for i, frame in enumerate(frames):
            tile = Image.new("RGBA", frame.size, "#172536")
            tile.alpha_composite(frame)
            tile = tile.convert("RGB")
            sheet.paste(tile.resize((frame.width * 2, frame.height * 2),
                                    Image.Resampling.NEAREST), (8 + i * frame.width * 2, y))
            sequence.append(tile.resize((frame.width * 4, frame.height * 4),
                                        Image.Resampling.NEAREST))
        sequence[0].save(out / entry["file"].replace(".png", ".gif"),
                         save_all=True, append_images=sequence[1:], loop=0,
                         duration=(entry["frame_ticks"] + 1) * 40, disposal=2)
        y += frames[0].height * 2 + 12
    sheet.save(out / "frames.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the checked-in header")
    args = parser.parse_args()
    manifest = json.loads((ASSETS / "manifest.json").read_text())
    animations = []
    for entry in manifest["assets"]:
        frames = load_frames(entry)
        data = pack(entry, frames)
        animations.append((entry, data, frames))
        print(f"{entry['symbol']}: {len(frames)} frames, {data[0]}-bit, {len(data)} bytes")
    text = header_text(animations)
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit("followers.h is out of date; run this script without --check")
    else:
        OUTPUT.write_text(text)
        previews(animations)


if __name__ == "__main__":
    main()
