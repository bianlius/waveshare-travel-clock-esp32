"""Derive a native 16px home badge from the existing alarm menu icon."""

from collections import deque
from pathlib import Path
import re

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "main/pic_data/pic_list/ICO_ring.h"
OUTPUT = ROOT / "main/pic_data/home/alarm_hint.h"
data = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]+)",
             SOURCE.read_text().split("{", 1)[1]))
assert data[:6] == bytes((4, 1, 0, 42, 0, 42))
palette = [int.from_bytes(data[9 + 2*i:11 + 2*i], "big") for i in range(15)]
mask = Image.new("L", (22, 22))
for y in range(22):
    for x in range(22):
        n = (y + 10) * 42 + x + 10
        index = (data[39 + n//2] >> (4*(n & 1))) & 15
        c = palette[index] if index < 15 else 0xFFFF
        r, g, b = (c >> 11)*255//31, ((c >> 5) & 63)*255//63, (c & 31)*255//31
        mask.putpixel((x, y), 255 if max(r, g, b) < 80 else 0)
mask = mask.resize((14, 14), Image.Resampling.NEAREST)
dark = {(x+1, y+1) for y in range(14) for x in range(14) if mask.getpixel((x, y))}
exterior = set()
queue = deque((x, y) for y in range(16) for x in range(16)
              if x in (0, 15) or y in (0, 15))
while queue:
    point = queue.popleft()
    x, y = point
    if point in exterior or point in dark or not (0 <= x < 16 and 0 <= y < 16):
        continue
    exterior.add(point)
    queue.extend(((x-1, y), (x+1, y), (x, y-1), (x, y+1)))
white = {(x, y) for y in range(16) for x in range(16) if (x, y) not in exterior | dark}
for x, y in dark:
    white.update((nx, ny) for nx, ny in ((x-1, y), (x+1, y), (x, y-1), (x, y+1))
                 if 0 <= nx < 16 and 0 <= ny < 16 and (nx, ny) not in dark)
pixels = [0 if (x, y) in dark else 1 if (x, y) in white else 15
          for y in range(16) for x in range(16)]
header = bytes((4, 1, 0, 16, 0, 16, 127, 127, 20))
colors = bytes.fromhex("08c3ffff") + bytes(26)
payload = bytes(pixels[i] | (pixels[i+1] << 4) for i in range(0, len(pixels), 2))
packed = header + colors + payload
lines = ["#ifndef GVIEW_ALARM_HINT_H", "#define GVIEW_ALARM_HINT_H",
         "// Generated by tools/pack_alarm_hint.py from ICO_ring.h.",
         "const unsigned char alarmHint[] = {"]
lines += ["    " + ",".join(f"0x{v:02x}" for v in packed[i:i+24]) + ","
          for i in range(0, len(packed), 24)]
OUTPUT.write_text("\n".join(lines + ["};", "#endif", ""]))
preview = Image.new("RGBA", (16, 16))
preview.putdata([(8, 24, 24, 255) if p == 0 else (255, 255, 255, 255)
                 if p == 1 else (0, 0, 0, 0) for p in pixels])
out = ROOT / "build/home-indicators"
out.mkdir(parents=True, exist_ok=True)
preview.save(out / "alarmHint.png")
