"""Pack the original garden sprout as an outlined, transparent home hint."""

from pathlib import Path
import re

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "main/pic_data/home/garden_miao.h"
OUTPUT = ROOT / "main/pic_data/home/garden_hint.h"
WIDTH, HEIGHT = 16, 20
PLANT_WIDTH, PLANT_HEIGHT = 12, 16
TRANSPARENT = 15

source_text = SOURCE.read_text().split("garden_miao[] = {", 1)[1].split("};", 1)[0]
source = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]+)", source_text))
assert source[0:2] == bytes((4, 2))
source_width = int.from_bytes(source[2:4], "big")
source_height = int.from_bytes(source[4:6], "big")
assert (source_width, source_height) == (19, 25)
palette_start = 2 + source[1] * 7
pixel_start = palette_start + 30
source_palette = [source[palette_start + index * 2:palette_start + index * 2 + 2]
                  for index in range(15)]


def pixel_index(packed, position):
    return (packed[position // 2] >> (4 * (position & 1))) & 15


source_pixels = source[pixel_start:pixel_start + (source_width * source_height + 1) // 2]
assert len(source_pixels) == (source_width * source_height + 1) // 2
sampled = []
for y in range(PLANT_HEIGHT):
    src_y = min(source_height - 1, ((2 * y + 1) * source_height) // (2 * PLANT_HEIGHT))
    for x in range(PLANT_WIDTH):
        src_x = min(source_width - 1, ((2 * x + 1) * source_width) // (2 * PLANT_WIDTH))
        sampled.append(pixel_index(source_pixels, src_y * source_width + src_x))

used = sorted(set(sampled) - {TRANSPARENT})
assert len(used) <= 13
remap = {original: compact for compact, original in enumerate(used)}
white = len(used)
pixels = [TRANSPARENT] * (WIDTH * HEIGHT)
core = {(x + 2, y + 2): remap[index]
        for y in range(PLANT_HEIGHT)
        for x in range(PLANT_WIDTH)
        if (index := sampled[y * PLANT_WIDTH + x]) != TRANSPARENT}
for x, y in core:
    for dy in range(-1, 2):
        for dx in range(-1, 2):
            if abs(dx) + abs(dy) <= 1 and 0 <= x + dx < WIDTH and 0 <= y + dy < HEIGHT:
                pixels[(y + dy) * WIDTH + x + dx] = white
for (x, y), index in core.items():
    pixels[y * WIDTH + x] = index

palette = b"".join(source_palette[index] for index in used)
palette += bytes((0xFF, 0xFF))  # White halo; the original dark outline remains.
palette += b"\0" * (30 - len(palette))
header = bytes((4, 1, 0, WIDTH, 0, HEIGHT, 0x7F, 0x7F, 20))
body = bytes(pixels[position] | (pixels[position + 1] << 4)
             for position in range(0, len(pixels), 2))
image_data = header + palette + body
assert len(image_data) == 9 + 30 + WIDTH * HEIGHT // 2

lines = [
    "#ifndef __GARDEN_HINT_H__",
    "#define __GARDEN_HINT_H__",
    "// Original garden_miao frame 0, sampled to 12x16 with a transparent edge.",
    "// Generated by tools/pack_garden_hint.py; palette index 15 is transparent.",
    "const unsigned char gardenHint[] = {",
]
for start in range(0, len(image_data), 16):
    lines.append("    " + ", ".join(f"0x{value:02x}" for value in image_data[start:start + 16]) + ",")
lines.extend(("};", "#endif"))
OUTPUT.write_text("\n".join(lines) + "\n")

preview = Image.new("RGB", (WIDTH * 12 * 2 + 48, HEIGHT * 12 + 24), "white")
draw = ImageDraw.Draw(preview)
for side, background in enumerate(((17, 27, 41), (234, 238, 230))):
    for y in range(HEIGHT):
        for x in range(WIDTH):
            position = y * WIDTH + x
            index = pixel_index(image_data[39:], position)
            if index == TRANSPARENT:
                color = background
            else:
                rgb = int.from_bytes(image_data[9 + index * 2:11 + index * 2], "big")
                color = (((rgb >> 11) & 31) * 255 // 31,
                         ((rgb >> 5) & 63) * 255 // 63,
                         (rgb & 31) * 255 // 31)
            left = 12 + side * (WIDTH * 12 + 24) + x * 12
            top = 12 + y * 12
            draw.rectangle((left, top, left + 11, top + 11), fill=color)
preview_path = ROOT / "build/garden_hint_original_style_preview.png"
preview_path.parent.mkdir(parents=True, exist_ok=True)
preview.save(preview_path)
print(preview_path)
